/** Пошук за будь-яким входженням тексту (початок, середина, кінець слова). */
export function searchProducts(list: Product[], query: string): Product[] {
  const q = query.trim().toLocaleLowerCase('uk');
  if (!q) return list;
  return list.filter((p) => `${p.name} ${p.article}`.toLocaleLowerCase('uk').includes(q));
}
